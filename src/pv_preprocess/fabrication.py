@dataclass(frozen=True)
class Hole:
    """구멍 무리 하나. view 는 부품도의 어느 뷰에 그리는가 (top/front/side/end)."""

    view: str
    n: int
    bolt: str           # "M16" — 지름은 HOLE_MM 에서, 탭이면 tapped=True
    pattern: str        # "row" | "corners" | "grid" | "pcd"
    along: str = "L"    # row: 어느 변을 따라 (L | W)
    edge: float = 30.0  # corners/row: 가장자리 거리
    pitch: float = 0.0  # row/grid 피치 (0 = 등분)
    pcd: float = 0.0    # pcd 패턴의 피치원 지름
    tapped: bool = False
    note: str = ""

    @property
    def dia_mm(self) -> float:
        return float(self.bolt[1:]) if self.tapped else HOLE_MM[self.bolt]

    @property
    def callout(self) -> str:
        if self.tapped:
            return f"{self.n}×{self.bolt} 탭"
        return f"{self.n}×Ø{self.dia_mm:g} ({self.bolt} 관통)"


@dataclass(frozen=True)
class Part:
    """제작품 하나. size 는 (L, W, H) mm — 도면 관례 (길이, 폭, 높이/두께)."""

    tag: str
    name: str
    kind: str            # plate | box | shs | tube | ring | cyl | bar | angle | channel | hbeam | weldment
    size: tuple[float, float, float]
    material: str
    t: float             # 판두께 / 관두께 mm (solid 는 0)
    qty: int
    process: str         # 제작 공정
    holes: tuple[Hole, ...] = ()
    finish: str = "블라스트 Sa2.5 · 에폭시 프라이머 60 µm + 우레탄 상도 60 µm RAL 7035"
    tolerance: str = "KS B ISO 2768-mK"
    note: str = ""

    @property
    def L(self) -> float:
        return self.size[0]

    @property
    def W(self) -> float:
        return self.size[1]

    @property
    def H(self) -> float:
        return self.size[2]

    def volume_mm3(self) -> float:
        L, W, H, t = self.L, self.W, self.H, self.t
        if self.kind == "plate":
            return L * W * H
        if self.kind == "disc":                    # 원판: Ø=L, t=H (중앙 구멍 W)
            return 3.14159 * ((L / 2) ** 2 - (W / 2) ** 2) * H
        if self.kind in ("box", "shs"):           # 각관·박스빔: 둘레 × t × L
            return (2 * (W + H) - 4 * t) * t * L
        if self.kind == "channel":                 # ㄷ형강: 웹 + 플랜지 2
            return (H * t + 2 * (W - t) * t) * L
        if self.kind == "angle":
            return (W * t + (H - t) * t) * L
        if self.kind == "hbeam":                   # H형강: 웹 t, 플랜지 1.4 t 근사
            return (2 * W * 1.4 * t + (H - 2.8 * t) * t) * L
        if self.kind == "tube":                    # 원관: L, OD=W, t
            r = W / 2
            return 3.14159 * (r * r - (r - t) * (r - t)) * L
        if self.kind == "ring":                    # 링: 중심선 지름 L, 관 OD W, t
            r = W / 2
            return 3.14159 * L * 3.14159 * (r * r - (r - t) * (r - t))
        if self.kind == "cyl":                     # 원통 동체: OD=L, H, t (t=0 이면 솔리드)
            r = L / 2
            if t <= 0:
                return 3.14159 * r * r * H
            return 3.14159 * (r * r - (r - t) * (r - t)) * H
        if self.kind == "bar":
            return L * W * H
        if self.kind == "weldment":                # 판 조립: 겉넓이 × t 근사
            return 2 * (L * W + W * H + H * L) * t * 0.6
        raise ValueError(self.kind)

    def weight_kg(self) -> float:
        return round(self.volume_mm3() * MATERIALS[self.material][3], 1)


