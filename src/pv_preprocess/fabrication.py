def summary() -> dict[str, object]:
    return {
        "assemblies": len(ASSEMBLIES),
        "fabricated_kinds": sum(len(a.parts) for a in ASSEMBLIES),
        "fabricated_pieces": sum(p.qty * a.qty for a in ASSEMBLIES for p in a.parts),
        "commercial_kinds": sum(len(a.commercial) for a in ASSEMBLIES),
        "bolts": sum(j.qty * a.qty for a in ASSEMBLIES for j in a.joints if j.kind in ("관통", "탭")),
        "anchors": sum(j.qty * a.qty for a in ASSEMBLIES for j in a.joints if j.kind == "앵커"),
        "weight_kg": plant_weight_kg(),
        "open_items": len(OPEN_ITEMS),
    }
