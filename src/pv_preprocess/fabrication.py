def joint_checks() -> list[str]:
    """체결의 형식 검사 — 문제 목록 (비어 있어야 한다)."""
    problems = []
    for a in ASSEMBLIES:
        for j in a.joints:
            if j.kind == "용접":
                continue
            if j.size not in TORQUE_NM:
                problems.append(f"{a.sheet} {j.name}: 토크표에 없는 호칭 {j.size}")
            if j.kind == "앵커" and j.size not in ANCHOR_EMBED_MM:
                problems.append(f"{a.sheet} {j.name}: 앵커 매입 깊이 없음 {j.size}")
        for p in a.parts:
            for h in p.holes:
                if h.bolt not in HOLE_MM:
                    problems.append(f"{a.sheet} {p.tag}: 구멍 호칭 {h.bolt}")
                if p.kind == "plate" and not h.tapped and h.pattern == "corners" and h.edge < 1.5 * HOLE_MM[h.bolt] / 1.0 * 0.5:
                    problems.append(f"{a.sheet} {p.tag}: 가장자리 거리 {h.edge} < 1.5 d")
    return problems


