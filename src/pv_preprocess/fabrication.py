@dataclass(frozen=True)
class Joint:
    """체결 하나 — 무엇을 무엇에, 어떤 볼트로 몇 개."""

    name: str
    parts: str           # "A ↔ B"
    bolt: str            # "M16×50"
    cls: str             # "8.8" | "10.9" | "앵커"
    qty: int
    kind: str = "관통"     # 관통 | 탭 | 앵커
    note: str = ""

    @property
    def size(self) -> str:
        return self.bolt.split("×")[0]

    @property
    def torque_nm(self) -> float:
        lo, hi = TORQUE_NM[self.size]
        return hi if self.cls == "10.9" else lo

    @property
    def hardware(self) -> str:
        if self.kind == "앵커":
            return f"케미컬 앵커 {self.bolt} 8.8 · 너트 · 평와셔 · 매입 {ANCHOR_EMBED_MM[self.size]}"
        if self.kind == "탭":
            return f"볼트 {self.bolt} {self.cls} · 스프링와셔 · 평와셔 · 나사고정제"
        return f"볼트 {self.bolt} {self.cls} · 너트 · 평와셔 2 · 스프링와셔"


@dataclass(frozen=True)
class Step:
    no: int
    title: str
    text: str
    tools: str = ""
    check: str = ""


@dataclass(frozen=True)
class Assembly:
    sheet: str
    tag: str
    name: str
    qty: int                  # 플랜트에 몇 벌
    scope: str
    parts: tuple[Part, ...]
    commercial: tuple[Commercial, ...]
    joints: tuple[Joint, ...]
    steps: tuple[Step, ...]
    inspection: tuple[str, ...]
    explode: tuple[tuple[str, tuple[float, float, float], tuple[float, float, float], tuple[float, float, float]], ...] = ()
    #: 분해도 인스턴스 — (부품 tag, size(X, 상하, 깊이), at, 분해 방향). 없으면 부품표 순서로 자동 배치.

    def fabricated_weight_kg(self) -> float:
        return round(sum(p.weight_kg() * p.qty for p in self.parts), 1)

    def bolt_count(self) -> int:
        return sum(j.qty for j in self.joints)


# ── 자주 쓰는 구멍 무리 ──────────────────────────────────────────────────
def corners(bolt: str, edge: float = 30.0, view: str = "top", note: str = "") -> Hole:
    return Hole(view, 4, bolt, "corners", edge=edge, note=note)


def row(n: int, bolt: str, along: str = "L", edge: float = 40.0, pitch: float = 0.0, view: str = "top",
        tapped: bool = False, note: str = "") -> Hole:
    return Hole(view, n, bolt, "row", along=along, edge=edge, pitch=pitch, tapped=tapped, note=note)


