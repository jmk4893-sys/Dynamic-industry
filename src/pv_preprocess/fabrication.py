def anchors_match_mounting() -> dict[str, tuple[int, int]]:
    """모델(mounting)과 제작 패키지의 앵커 수 대조 — 셀별 (모델, 패키지).

    afu 12×M20 → 벽체 3 × 4. bfc 포탈기둥 4×M20 ×4기 → Bay 1식 16 (플랜트 32).
    robot 8×M24 + PT 8×M16 → 페데스털 8 + 정반 8.
    """
    model = {
        "afu M20": next(a.count * a.units for m in mounting.MOUNTINGS if m.station == "afu" for a in m.anchors if a.bolt == "M20"),
        "bfc M20": next(a.count * a.units for m in mounting.MOUNTINGS if m.station == "bfc" for a in m.anchors) * 2,
        "robot M24": next(a.count for m in mounting.MOUNTINGS if m.station == "robot" for a in m.anchors if a.bolt == "M24"),
        "robot M16": next(a.count for m in mounting.MOUNTINGS if m.station == "robot" for a in m.anchors if a.bolt == "M16"),
    }
    pkg = {
        "afu M20": sum(j.qty * a.qty for a in ASSEMBLIES if a.tag == "AFU-BW-101" for j in a.joints if j.kind == "앵커"),
        "bfc M20": sum(j.qty * a.qty for a in ASSEMBLIES if a.tag == "AFU-BFC-101" for j in a.joints if j.kind == "앵커"),
        "robot M24": sum(j.qty for a in ASSEMBLIES if a.tag.startswith("AFU-RB-101") for j in a.joints if j.kind == "앵커"),
        "robot M16": sum(j.qty for a in ASSEMBLIES if a.tag.startswith("AFU-PT-101") for j in a.joints if j.kind == "앵커"),
    }
    return {k: (model[k], pkg[k]) for k in model}


