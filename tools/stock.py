def pieces(total: float, sheet_side: float, trim: float = PLATE_TRIM) -> int:
    """길이 total 을 시트 한 변(sheet_side)에서 나오게 하려면 몇 조각으로 나누는가."""
    return max(1, math.ceil(total / (sheet_side - 2 * trim) - 1e-9))


def bar_pieces(total: float) -> int:
    """정척보다 긴 선형재를 몇 토막으로 이어 붙이는가 — 이음 하나마다 절단 손실을 본다."""
    usable = max(BAR_STOCK) - BAR_TRIM
    n = 1
    while total / n + CUT_KERF > usable:
        n += 1
    return n
