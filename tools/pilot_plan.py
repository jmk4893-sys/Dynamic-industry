def panel_budget() -> list[tuple[str, int, str]]:
    """신품 소요만 센다. 시행 수를 그냥 더하면 두 배가 넘게 나온다 —
    한 장을 통과시키면 박리력·수율·균일도·배기·열수지가 **한꺼번에**
    나오기 때문이다. 패널은 한 번만 박리된다."""
    ts = tests()
    p1 = [t for t in ts if t.phase == 1]
    p2 = [t for t in ts if t.phase == 2]
    n1 = sum(t.n_new for t in p1)
    n2 = sum(t.n_new for t in p2)
    return [
        (f"1 단계 ({' · '.join(t.id for t in p1)})", n1,
         f"시행은 {sum(t.n for t in p1)} 회지만 신품은 {n1} 장이다 — "
         f"한 장의 통과에서 여러 시험이 함께 나온다. 이 안에서 줄이면 "
         f"정밀도가 요구를 못 맞춘다"),
        (f"2 단계 ({' · '.join(t.id for t in p2)})", n2,
         "**파일럿의 크기를 정하는 것은 여기다.** 칼날 수명 300 장이 "
         "1 단계 전체보다 크다. 박리력 곡선만 원하면 1 단계로 끝난다"),
        ("합계", n1 + n2,
         "폐패널 조달이 이 계획의 첫 관문이다. 로트 D 300 장을 "
         "동일 제조사·동일 로트로 모을 수 있는지가 2 단계의 전제다. "
         f"전 로트를 {SPECIMEN_STATE} 로 준비한다 — {SPECIMEN_PREP}"),
    ]


