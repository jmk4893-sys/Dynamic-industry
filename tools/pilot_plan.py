# ── 시료 수 — 요구정밀도에서 거꾸로 푼다 ─────────────────────────────
def _t975(df: int) -> float:
    """t(0.975, df) — 스튜던트 t 의 양측 95 % 분위수.

    처음에는 Cornish–Fisher 계열 근사식을 썼다. 자유도가 크면 잘 맞지만
    **df = 1 에서 12.706 을 9.71 로 냈다** — 24 % 낮다. 그런데 시료 수를
    찾는 반복은 n = 2 (df = 1) 에서 시작하므로, 하필 근사가 가장 나쁜
    자리를 가장 먼저 밟는다. 요구가 느슨하면 그 자리에서 멈춰 시료 수가
    조용히 작게 나온다.

    그래서 근사하지 않는다. t 의 확률밀도를 심프슨으로 적분해 누적분포를
    만들고, ∫₀ᵗ f = 0.475 가 되는 t 를 이분법으로 찾는다. 표값과
    1e-4 안에서 맞는다.
    """
    if df < 1:
        return float("inf")
    lc = (math.lgamma((df + 1) / 2) - math.lgamma(df / 2)
          - 0.5 * math.log(df * math.pi))
    exp = -(df + 1) / 2

    def pdf(x: float) -> float:
        return math.exp(lc + exp * math.log1p(x * x / df))

    def half(t: float, n: int = 2000) -> float:
        """∫₀ᵗ f dx — 심프슨. n 은 짝수."""
        h = t / n
        s = pdf(0.0) + pdf(t)
        for i in range(1, n):
            s += pdf(i * h) * (4 if i % 2 else 2)
        return s * h / 3

    lo, hi = 0.0, 400.0
    for _ in range(80):
        mid = (lo + hi) / 2
        if half(mid) < 0.475:
            lo = mid
        else:
            hi = mid
    return (lo + hi) / 2


def n_for_mean(cv: float, half_width: float, n_max: int = 400) -> int:
    """평균을 상대반폭 half_width 안에서 잡는 데 필요한 시료 수.

    n = (t(n−1)·CV / E)² — t 가 n 에 걸려 있으므로 커지며 찾는다.
    """
    for n in range(2, n_max + 1):
        if _t975(n - 1) * cv / math.sqrt(n) <= half_width:
            return n
    return n_max


def _cp_lower(k: int, n: int, alpha: float = 0.05) -> float:
    """Clopper–Pearson 하한 — n 회 중 k 회 실패했을 때 성공률의 하한.

    베타 분포의 역함수를 이분법으로 찾는다. 정규근사를 쓰면 실패 0 회에서
    하한이 1.0 으로 나와 "무한히 좋다" 가 된다 — 그 답은 시료 수를 정할
    때 쓸 수 없다.
    """
    s = n - k                                   # 성공 횟수
    if s == n:
        return alpha ** (1.0 / n)               # 실패 0 회의 닫힌해
    lo, hi = 0.0, 1.0
    for _ in range(200):
        p = (lo + hi) / 2
        # P[성공 ≥ s | p] — 이 값이 alpha 가 되는 p 가 하한
        tail = sum(math.comb(n, i) * p ** i * (1 - p) ** (n - i)
                   for i in range(s, n + 1))
        if tail > alpha:
            hi = p
        else:
            lo = p
    return (lo + hi) / 2


def n_for_proportion(target: float, failures: int = 0, n_max: int = 600) -> int:
    """실패 failures 회를 허용하고도 하한이 target 을 넘는 최소 시료 수."""
    for n in range(failures + 1, n_max + 1):
        if _cp_lower(failures, n) >= target:
            return n
    return n_max


