# ── 1. 형상족 ──────────────────────────────────────────────────────────
# 부품도가 그릴 수 있는 형상은 열두 가지뿐이다. 이 목록 밖의 형상이
# 필요해지면 도면 생성기에 투상을 하나 더 넣어야 한다 — 형상족을 늘리지
# 않고 "기타" 로 넘기면 그 부품은 그림 없이 표만 남는다.
#
# 각 족의 vol() 은 mm³ 를 돌려준다. 질량은 vol × 밀도이므로, 형상을
# 고치면 질량표와 자중 검증이 함께 움직인다.

class Shape(NamedTuple):
    kind: str
    d: dict

    def vol(self) -> float:
        return _VOL[self.kind](self.d)

    def label(self) -> str:
        return _LBL[self.kind](self.d)

    def bbox(self) -> tuple[float, float, float]:
        """외형 상자 (L, W, H) mm — 조립도 분해 간격과 포장 치수의 근거."""
        return _BOX[self.kind](self.d)


def PL(L, W, t, holes=(), name="", hnote="") -> Shape:
    """평판. holes = ((x, y, d), …) — 판 좌하단 기준 mm. hnote 는 구멍 주기 —
    비우면 부품도가 '관통 · 위치공차 ±0.5' 로 적는다 (접시·탭처럼 다른 구멍만 적는다)."""
    d = dict(L=L, W=W, t=t, holes=tuple(holes), name=name)
    if hnote:
        d["hnote"] = hnote
    return Shape("PL", d)


def HB(h, b, tw, tf, L) -> Shape:
    """H 형강."""
    return Shape("HB", dict(h=h, b=b, tw=tw, tf=tf, L=L))


def BOX(h, b, t, L) -> Shape:
    """각형강관 · 박스거더."""
    return Shape("BOX", dict(h=h, b=b, t=t, L=L))


def ANG(a, b, t, L) -> Shape:
    """ㄱ 형강."""
    return Shape("ANG", dict(a=a, b=b, t=t, L=L))


def CH(h, b, tw, tf, L) -> Shape:
    """ㄷ 형강."""
    return Shape("CH", dict(h=h, b=b, tw=tw, tf=tf, L=L))


def SQB(a, L) -> Shape:
    """각봉."""
    return Shape("SQB", dict(a=a, L=L))


def RB(d, L, steps=()) -> Shape:
    """환봉·축. steps = ((d, l), …) 이면 단차축."""
    return Shape("RB", dict(d=d, L=L, steps=tuple(steps)))


def TU(od, t, L) -> Shape:
    """관."""
    return Shape("TU", dict(od=od, t=t, L=L))


def FL(od, idd, t, pcd, n, dh) -> Shape:
    """원형 플랜지."""
    return Shape("FL", dict(od=od, id=idd, t=t, pcd=pcd, n=n, dh=dh))


def GU(a, b, t) -> Shape:
    """삼각 거싯."""
    return Shape("GU", dict(a=a, b=b, t=t))


def MESH(L, W, wire, pitch, frame) -> Shape:
    """메시 패널 — 테두리 앵글 + 격자."""
    return Shape("MESH", dict(L=L, W=W, wire=wire, pitch=pitch, frame=frame))


def SLAB(L, W, t) -> Shape:
    """비금속 판재 (단열재·폴리카보네이트·GFRP). 밀도는 재질이 든다."""
    return Shape("SLAB", dict(L=L, W=W, t=t))


def BUY(L, W, H, kg) -> Shape:
    """구매품 — 외형 상자와 카탈로그 질량. 내부 형상은 그리지 않는다."""
    return Shape("BUY", dict(L=L, W=W, H=H, kg=kg))


_VOL = {
    "PL":   lambda d: d["L"] * d["W"] * d["t"]
                      - sum(math.pi / 4 * h[2] ** 2 * d["t"] for h in d["holes"]),
    "HB":   lambda d: (2 * d["b"] * d["tf"] + (d["h"] - 2 * d["tf"]) * d["tw"]) * d["L"],
    "BOX":  lambda d: (d["h"] * d["b"] - (d["h"] - 2 * d["t"]) * (d["b"] - 2 * d["t"])) * d["L"],
    "ANG":  lambda d: (d["a"] + d["b"] - d["t"]) * d["t"] * d["L"],
    "CH":   lambda d: (2 * d["b"] * d["tf"] + (d["h"] - 2 * d["tf"]) * d["tw"]) * d["L"],
    "SQB":  lambda d: d["a"] ** 2 * d["L"],
    "RB":   lambda d: (sum(math.pi / 4 * s[0] ** 2 * s[1] for s in d["steps"])
                       if d["steps"] else math.pi / 4 * d["d"] ** 2 * d["L"]),
    "TU":   lambda d: math.pi / 4 * (d["od"] ** 2 - (d["od"] - 2 * d["t"]) ** 2) * d["L"],
    "FL":   lambda d: math.pi / 4 * (d["od"] ** 2 - d["id"] ** 2) * d["t"]
                      - d["n"] * math.pi / 4 * d["dh"] ** 2 * d["t"],
    "GU":   lambda d: d["a"] * d["b"] / 2 * d["t"],
    "MESH": lambda d: (math.pi / 4 * d["wire"] ** 2
                       * ((d["L"] // d["pitch"] + 1) * d["W"] + (d["W"] // d["pitch"] + 1) * d["L"])
                       + 2 * (d["L"] + d["W"]) * d["frame"] * 30),
    "SLAB": lambda d: d["L"] * d["W"] * d["t"],
    "BUY":  lambda d: 0.0,          # 질량은 카탈로그 값을 쓴다
}

_f = lambda v: f"{v:,.0f}" if abs(v - round(v)) < 0.05 else f"{v:,.1f}"

