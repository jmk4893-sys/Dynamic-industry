# ── 3. 자중 검증 ───────────────────────────────────────────────────────
# 제작 지침서는 자중 넷을 가정으로 놓고 앵커·용접·접합부를 정했다. 이
# 카탈로그는 형상에서 질량을 계산하므로, 그 가정을 처음으로 검산한다.
#
# 비교는 **같은 것끼리** 해야 한다. 지침서의 M_GANTRY 는 갠트리 *이동부*
# (크로스빔·대차·Z슬라이드·칼날·카세트)이지 주행 문형까지가 아니고,
# M_WINDER 는 권취 *문형*이지 RH-201 런웨이까지가 아니다. 그래서 모듈
# 전체가 아니라 지침서가 세는 범위를 품번으로 집어 대조한다 — 범위를
# 흐리면 검산이 아니라 숫자 맞추기가 된다.
#
# ±15 % 를 벗어나면 앵커·기초를 다시 본다. 일곱 개소 전부 콘크리트 콘
# 파괴가 지배하므로, 자중이 늘면 매입깊이가 규격보다 먼저 움직인다.
MASS_TOL = 0.15

# 개념설계가 개산으로 놓았던 값 (kg). 이제는 설계가 이 값을 쓰지 않는다 —
# 지침서가 아래 group_kg() 를 가져간다. 여기 남기는 것은 기록이고, 개산이
# 얼마나 빗나갔는지가 곧 "왜 형상 없이 자중을 적으면 안 되는가" 의 답이다.
MASS_CONCEPT = {"M_CHAMBER": 6701, "M_TABLE": 900, "M_GANTRY": 1450, "M_WINDER": 620}

# (지침서 기호, 무엇을 세는가, 그 범위의 품번)
MASS_GROUPS = (
    ("M_CHAMBER", "가열실 일식 (골조·벽체·데크·IR)",
     [p.pid for p in P if p.mod == "M-002"]),
    ("M_TABLE", "VT-101 상판·리브·기둥·진공계통",
     [p.pid for p in P if p.mod == "M-004"]),
    ("M_GANTRY", "갠트리 이동부 (주행 문형·레일 제외)",
     ["P-005-06", "P-005-07", "P-005-08", "P-005-10", "P-005-11", "P-005-12",
      "P-005-13", "P-005-14", "P-005-15", "P-005-16", "P-005-17", "P-005-18",
      "P-005-19", "P-005-20", "P-005-21", "P-005-22"]),
    ("M_WINDER", "권취 문형 (RH-201 런웨이 제외)",
     ["P-006-01", "P-006-02", "P-006-03", "P-006-04", "P-006-05", "P-006-06",
      "P-006-07", "P-006-08", "P-006-09", "P-006-10", "P-006-11", "P-006-12",
      "P-006-13", "P-006-14", "P-006-15"]),
)


def group_kg(pids) -> float:
    idx = {p.pid: p for p in P}
    return sum(idx[i].total_kg for i in pids)


def mass(sym: str) -> float:
    """설계가 쓰는 자중 — 형상에서 계산한 값. 지침서가 이 함수를 가져간다."""
    for s_, _what, pids in MASS_GROUPS:
        if s_ == sym:
            return group_kg(pids)
    raise KeyError(sym)


def mass_check() -> list[tuple[str, str, float, float, float, bool]]:
    """(기호, 범위, 개념 개산, 형상 계산, 편차, 개산이 ±15 % 안이었나)."""
    out = []
    for sym, what, pids in MASS_GROUPS:
        a, got = MASS_CONCEPT[sym], group_kg(pids)
        dev = (got - a) / a
        out.append((sym, what, a, got, dev, abs(dev) <= MASS_TOL))
    return out


def module_kg(mod: str) -> float:
    return sum(p.total_kg for p in P if p.mod == mod)


