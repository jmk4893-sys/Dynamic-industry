# ── 1. 형상족 ──────────────────────────────────────────────────────────
# 부품도가 그릴 수 있는 형상은 열두 가지뿐이다. 이 목록 밖의 형상이
# 필요해지면 도면 생성기에 투상을 하나 더 넣어야 한다 — 형상족을 늘리지
# 않고 "기타" 로 넘기면 그 부품은 그림 없이 표만 남는다.
#
# 각 족의 vol() 은 mm³ 를 돌려준다. 질량은 vol × 밀도이므로, 형상을
# 고치면 질량표와 자중 검증이 함께 움직인다.

class Shape(NamedTuple):
    kind: str
    d: dict

    def vol(self) -> float:
        return _VOL[self.kind](self.d)

    def label(self) -> str:
        return _LBL[self.kind](self.d)

    def bbox(self) -> tuple[float, float, float]:
        """외형 상자 (L, W, H) mm — 조립도 분해 간격과 포장 치수의 근거."""
        return _BOX[self.kind](self.d)


def PL(L, W, t, holes=(), name="") -> Shape:
    """평판. holes = ((x, y, d), …) — 판 좌하단 기준 mm."""
    return Shape("PL", dict(L=L, W=W, t=t, holes=tuple(holes), name=name))


def HB(h, b, tw, tf, L) -> Shape:
    """H 형강."""
    return Shape("HB", dict(h=h, b=b, tw=tw, tf=tf, L=L))


def BOX(h, b, t, L) -> Shape:
    """각형강관 · 박스거더."""
    return Shape("BOX", dict(h=h, b=b, t=t, L=L))


def ANG(a, b, t, L) -> Shape:
    """ㄱ 형강."""
    return Shape("ANG", dict(a=a, b=b, t=t, L=L))


def CH(h, b, tw, tf, L) -> Shape:
    """ㄷ 형강."""
    return Shape("CH", dict(h=h, b=b, tw=tw, tf=tf, L=L))


def SQB(a, L) -> Shape:
    """각봉."""
    return Shape("SQB", dict(a=a, L=L))


def RB(d, L, steps=()) -> Shape:
    """환봉·축. steps = ((d, l), …) 이면 단차축."""
    return Shape("RB", dict(d=d, L=L, steps=tuple(steps)))


def TU(od, t, L) -> Shape:
    """관."""
    return Shape("TU", dict(od=od, t=t, L=L))


def FL(od, idd, t, pcd, n, dh) -> Shape:
    """원형 플랜지."""
    return Shape("FL", dict(od=od, id=idd, t=t, pcd=pcd, n=n, dh=dh))


def GU(a, b, t) -> Shape:
    """삼각 거싯."""
    return Shape("GU", dict(a=a, b=b, t=t))


def MESH(L, W, wire, pitch, frame) -> Shape:
    """메시 패널 — 테두리 앵글 + 격자."""
    return Shape("MESH", dict(L=L, W=W, wire=wire, pitch=pitch, frame=frame))


def SLAB(L, W, t) -> Shape:
    """비금속 판재 (단열재·폴리카보네이트·GFRP). 밀도는 재질이 든다."""
    return Shape("SLAB", dict(L=L, W=W, t=t))


def BUY(L, W, H, kg) -> Shape:
    """구매품 — 외형 상자와 카탈로그 질량. 내부 형상은 그리지 않는다."""
    return Shape("BUY", dict(L=L, W=W, H=H, kg=kg))


_VOL = {
    "PL":   lambda d: d["L"] * d["W"] * d["t"]
                      - sum(math.pi / 4 * h[2] ** 2 * d["t"] for h in d["holes"]),
    "HB":   lambda d: (2 * d["b"] * d["tf"] + (d["h"] - 2 * d["tf"]) * d["tw"]) * d["L"],
    "BOX":  lambda d: (d["h"] * d["b"] - (d["h"] - 2 * d["t"]) * (d["b"] - 2 * d["t"])) * d["L"],
    "ANG":  lambda d: (d["a"] + d["b"] - d["t"]) * d["t"] * d["L"],
    "CH":   lambda d: (2 * d["b"] * d["tf"] + (d["h"] - 2 * d["tf"]) * d["tw"]) * d["L"],
    "SQB":  lambda d: d["a"] ** 2 * d["L"],
    "RB":   lambda d: (sum(math.pi / 4 * s[0] ** 2 * s[1] for s in d["steps"])
                       if d["steps"] else math.pi / 4 * d["d"] ** 2 * d["L"]),
    "TU":   lambda d: math.pi / 4 * (d["od"] ** 2 - (d["od"] - 2 * d["t"]) ** 2) * d["L"],
    "FL":   lambda d: math.pi / 4 * (d["od"] ** 2 - d["id"] ** 2) * d["t"]
                      - d["n"] * math.pi / 4 * d["dh"] ** 2 * d["t"],
    "GU":   lambda d: d["a"] * d["b"] / 2 * d["t"],
    "MESH": lambda d: (math.pi / 4 * d["wire"] ** 2
                       * ((d["L"] // d["pitch"] + 1) * d["W"] + (d["W"] // d["pitch"] + 1) * d["L"])
                       + 2 * (d["L"] + d["W"]) * d["frame"] * 30),
    "SLAB": lambda d: d["L"] * d["W"] * d["t"],
    "BUY":  lambda d: 0.0,          # 질량은 카탈로그 값을 쓴다
}

_f = lambda v: f"{v:,.0f}" if abs(v - round(v)) < 0.05 else f"{v:,.1f}"

_LBL = {
    "PL":   lambda d: f"PL {_f(d['t'])}t · {_f(d['L'])}×{_f(d['W'])}",
    "HB":   lambda d: f"H-{_f(d['h'])}×{_f(d['b'])}×{_f(d['tw'])}/{_f(d['tf'])} · L {_f(d['L'])}",
    "BOX":  lambda d: f"□-{_f(d['h'])}×{_f(d['b'])}×{_f(d['t'])}t · L {_f(d['L'])}",
    "ANG":  lambda d: f"L-{_f(d['a'])}×{_f(d['b'])}×{_f(d['t'])} · L {_f(d['L'])}",
    "CH":   lambda d: f"C-{_f(d['h'])}×{_f(d['b'])}×{_f(d['tw'])}/{_f(d['tf'])} · L {_f(d['L'])}",
    "SQB":  lambda d: f"각봉 {_f(d['a'])}×{_f(d['a'])} · L {_f(d['L'])}",
    "RB":   lambda d: (f"Ø{_f(d['d'])} · L {_f(d['L'])}" if not d["steps"] else
                       "단차축 " + " / ".join(f"Ø{_f(s[0])}×{_f(s[1])}" for s in d["steps"])),
    "TU":   lambda d: f"Ø{_f(d['od'])} × {_f(d['t'])}t · L {_f(d['L'])}",
    "FL":   lambda d: f"플랜지 Ø{_f(d['od'])}/Ø{_f(d['id'])} × {_f(d['t'])}t · PCD {_f(d['pcd'])}-{d['n']}×Ø{_f(d['dh'])}",
    "GU":   lambda d: f"거싯 {_f(d['a'])}×{_f(d['b'])} × {_f(d['t'])}t",
    "MESH": lambda d: f"메시 Ø{_f(d['wire'])}@{_f(d['pitch'])} · {_f(d['L'])}×{_f(d['W'])}",
    "SLAB": lambda d: f"{_f(d['t'])}t · {_f(d['L'])}×{_f(d['W'])}",
    "BUY":  lambda d: f"외형 {_f(d['L'])}×{_f(d['W'])}×{_f(d['H'])}",
}

_BOX = {
    "PL":   lambda d: (d["L"], d["W"], d["t"]),
    "HB":   lambda d: (d["L"], d["b"], d["h"]),
    "BOX":  lambda d: (d["L"], d["b"], d["h"]),
    "ANG":  lambda d: (d["L"], d["b"], d["a"]),
    "CH":   lambda d: (d["L"], d["b"], d["h"]),
    "SQB":  lambda d: (d["L"], d["a"], d["a"]),
    "RB":   lambda d: (d["L"], d["d"], d["d"]),
    "TU":   lambda d: (d["L"], d["od"], d["od"]),
    "FL":   lambda d: (d["t"], d["od"], d["od"]),
    "GU":   lambda d: (d["a"], d["t"], d["b"]),
    "MESH": lambda d: (d["L"], 40.0, d["W"]),
    "SLAB": lambda d: (d["L"], d["W"], d["t"]),
    "BUY":  lambda d: (d["L"], d["W"], d["H"]),
}

# 비금속 밀도 (kg/m³) — MATERIALS 에 없는 것만 여기서 든다.
RHO_OTHER = {
    "미네랄울": 100, "GFRP": 1900, "PC": 1200, "NBR": 1400,
    "AL반사판": 2700, "세라믹파이버": 260, "동": 8960, "—": 0,
}


def density(mat: str) -> float:
    """밀도 kg/m³. 금속은 지침서의 MATERIALS 가 든다 — 두 곳에 적지 않는다.

    지침서를 함수 안에서 읽는 이유: 지침서가 이 카탈로그에서 자중을 가져가므로,
    최상단에서 서로를 읽으면 순환이 된다.
    """
    from fab_spec import MATERIALS
    if mat in MATERIALS:
        return MATERIALS[mat]["rho"]
    return RHO_OTHER.get(mat, 0)


# ── 2. 부품 ────────────────────────────────────────────────────────────
class Part(NamedTuple):
    pid: str            # 도번
    mod: str            # 모듈
    name: str
    shape: Shape
    mat: str
    finish: str
    qty: int            # 기계 1대분 수량
    fix: str            # 어떻게 붙는가 — 체결구 또는 용접
    note: str
    step: int           # 조립 순서 단계 (모듈 안에서)

    @property
    def buy(self) -> bool:
        return self.shape.kind == "BUY"

    @property
    def kg(self) -> float:
        """1개 질량. 구매품은 카탈로그 값, 제작품은 형상에서 계산."""
        if self.buy:
            return self.shape.d["kg"]
        return self.shape.vol() * density(self.mat) / 1e9

    @property
    def total_kg(self) -> float:
        return self.kg * self.qty


P: list[Part] = []


def add(pid, mod, name, shape, mat, finish, qty, fix, note, step):
    P.append(Part(pid, mod, name, shape, mat, finish, qty, fix, note, step))


