def _fence_runs():
    """(구간 목록, 게이트 수) — 콘솔 cFence 와 같은 순서로 세운다."""
    runs = []

    def gate(y, x0, x1):
        runs.append(((x0, y), (_GATE_X - _GATE_W / 2, y)))
        runs.append(((_GATE_X + _GATE_W / 2, y), (x1, y)))

    if TWIN:
        for sg, nf in ((-1, _NN), (1, _NP)):
            runs.extend((((_FX0, sg * nf), (_DX0, sg * nf)), ((_DX1, sg * nf), (_FX1, sg * nf)),
                         ((_DX0, sg * nf), (_DX0, sg * FENCE_P)), ((_DX1, sg * nf), (_DX1, sg * FENCE_P))))
            gate(sg * FENCE_P, _DX0, _DX1)
        gates = 2
    else:
        gate(-FENCE_N, _FX0, _FX1)
        runs.append(((_FX0, FENCE_P), (_FX1, FENCE_P)))
        gates = 1
    for x in (_FX0, _FX1):
        runs.extend((((x, -_NN), (x, -_OPEN)), ((x, _OPEN), (x, _NP))))
    return runs, gates


def _bays(runs, pitch):
    """(길이 합 mm, 칸 수, 기둥 수) — 구간 끝 기둥은 이웃 구간과 나눠 쓴다."""
    total = bays = inner = 0
    ends = set()
    for (x0, y0), (x1, y1) in runs:
        L = math.hypot(x1 - x0, y1 - y0)
        if L < 20:
            continue
        n = math.ceil(L / pitch - 1e-9)
        total, bays, inner = total + L, bays + n, inner + n - 1
        ends |= {(round(x0), round(y0)), (round(x1), round(y1))}
    return total, bays, len(ends) + inner


