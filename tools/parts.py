# 셀 수가 곱해져 들어간다 — 부품도·발주·운반이 같은 수를 보게. 자중처럼 "한 벌" 을
# 봐야 하는 계산은 unit_qty() 로 나눠 본다 (앵커는 셀 하나의 테이블을 받친다).
PER_CELL = ("M-004", "M-005", "M-008")
_PER_CELL_PIDS: set = set()


def add(pid, mod, name, shape, mat, finish, qty, fix, note, step, per_cell=None):
    """부품 하나. per_cell 을 비우면 모듈이 정한다 — 공용 모듈 안의 셀별 부품
    (KC-101 매거진)은 per_cell=True 로 따로 적는다."""
    if per_cell is None:
        per_cell = mod in PER_CELL
    if per_cell:
        qty *= CELLS
        _PER_CELL_PIDS.add(pid)
    P.append(Part(pid, mod, name, shape, mat, finish, qty, fix, note, step))


def is_per_cell(p) -> bool:
    return p.pid in _PER_CELL_PIDS


def unit_qty(p) -> int:
    """셀 하나(셀별 부품) 또는 기계 하나(공용 부품)의 수량."""
    return p.qty // CELLS if is_per_cell(p) else p.qty


