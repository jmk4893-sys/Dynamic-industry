def anchor_group(aid):
    return next(a for a in ANCHOR_GROUPS if a[0] == aid)


def anchor_label(pid):
    """판 품번이 받는 기호 — 포크 넷처럼 한 판이 여러 군이면 'A3~A6'."""
    ids = [a[0] for a in ANCHOR_GROUPS if a[2] == pid]
    return ids[0] if len(ids) == 1 else f"{ids[0]}~{ids[-1]}"


def anchor_fix(pid, holes, lead="앵커"):
    """베이스플레이트의 체결 칸 — 기호 · 규격 · 매입깊이를 표에서, 수를 구멍에서 낸다."""
    g = next(a for a in ANCHOR_GROUPS if a[2] == pid)
    return f"{lead} {g[3]} ({anchor_label(pid)}) ×{len(holes)} · hef {g[4]}"


