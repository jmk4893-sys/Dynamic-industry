"""DG-HK60C 부품 카탈로그 — 형상·치수·재질·질량.

제작 지침서(fab_spec.py)가 정한 것은 "얼마나 두껍게" 까지다. 제작사가
부품을 깎으려면 "어떻게 생겼는가" 가 있어야 하고, 조립하려면 "어디에
어떻게 붙는가" 가 있어야 한다. 이 파일이 그 둘을 든다.

원칙은 지침서와 같다 — **값이 아니라 식**.

  · 치수는 콘솔 상수에서 유도한다. 랙 길이는 DECK_L+2·CL_WALL+CL_DOOR 이고
    단 높이는 cDeckZ(k) 다. 상수가 움직이면 부품 길이가 따라 움직인다.
  · **질량은 형상에서 계산한다.** 부재 단면적 × 길이 × 밀도. 그래서 이
    카탈로그는 지침서가 가정으로 쓴 자중 넷을 검증하는 장치이기도 하다
    (§ MASS_CHECK). 가정과 계산이 ±15 % 를 벗어나면 앵커를 다시 본다.
  · 구매품은 형상을 그리지 않는다. 외형 상자와 규격·장착면만 적는다 —
    사는 물건의 내부 치수를 도면에 적으면 그것은 거짓말이다.

이 카탈로그의 지위: 개념설계가 유도한 형상이다. 상세설계에서 확정한다.
그때 바뀌는 것은 이 파일의 숫자이고, 부품도·조립도·질량표는 따라온다.
"""

